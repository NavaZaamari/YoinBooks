export const articles = [readingArticle];
export type BlogArticle = typeof readingArticle;
export const articlePath = (article: BlogArticle) => `/blog/${article.slug}`;
export const readingMinutes = (article: BlogArticle) => {
  const text = [
    ...article.intro,
    ...article.sections.flatMap((s) => [
      s.title,
      ...s.paragraphs,
      ...(s.subsections ?? []).flatMap((sub) => [sub.title, ...sub.paragraphs]),
    ]),
  ]
    .map((p) => (typeof p === "string" ? p : `${p.before} ${p.label} ${p.after}`))
    .join(" ");
  return Math.max(1, Math.ceil(text.trim().split(/\s+/u).length / 180));
};
